#!/usr/bin/env python3
"""Rebuild guide/rules-index.md from the `## Checklist` tables of the rule files.

Run from the repository root:  python3 tools/build_rules_index.py
"""
import re
import sys
from pathlib import Path

GUIDE = Path(__file__).resolve().parent.parent / "guide"
OUT = GUIDE / "rules-index.md"

ROW = re.compile(r"^\|\s*([A-Z]{3}-\d{2})\s*\|(.*)\|\s*$")


def rows_of(path: Path):
    text = path.read_text(encoding="utf-8")
    if "## Checklist" not in text:
        return []
    table = text.split("## Checklist", 1)[1]
    out = []
    for line in table.splitlines():
        m = ROW.match(line)
        if not m:
            continue
        rule_id = m.group(1)
        cells = [c.strip() for c in m.group(2).split("|")]
        # cells: [summary, apply] or [summary, since, apply]
        summary = cells[0]
        apply = cells[-1]
        since = cells[1] if len(cells) == 3 else ""
        out.append((rule_id, summary, since, apply))
    return out


def anchor(rule_id: str, path: Path) -> str:
    """GitHub-style anchor of the `## RULE-ID Title` heading."""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith(f"## {rule_id} "):
            title = line[3:].strip().lower()
            title = re.sub(r"[`*_()]", "", title)
            title = re.sub(r"[^a-z0-9 \-]", "", title)
            return "#" + re.sub(r"\s+", "-", title.strip())
    sys.exit(f"no heading for {rule_id} in {path.name}")


def main() -> None:
    files = sorted(p for p in GUIDE.glob("[0-9][0-9]-*.md") if p.name != "00-procedure.md")
    lines = [
        "# Rules Index",
        "",
        "Generated by `tools/build_rules_index.py` from the checklist table of each rule file. "
        "Do not edit by hand; edit the rule file's checklist and rerun the script.",
        "",
        "Apply levels: `auto` exact transformation, recompile; `assisted` confirm intent, then edit; "
        "`advisory` report with a suggestion only. See [README.md](README.md).",
        "",
    ]
    total = 0
    seen = set()
    for path in files:
        rows = rows_of(path)
        if not rows:
            continue
        title = path.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
        lines += [f"## {title}", "", f"File: [{path.name}]({path.name})", ""]
        has_since = any(r[2] for r in rows)
        lines.append("| ID | Rule | Since | Apply |" if has_since else "| ID | Rule | Apply |")
        lines.append("|----|------|-------|-------|" if has_since else "|----|------|-------|")
        for rule_id, summary, since, apply in rows:
            if rule_id in seen:
                sys.exit(f"duplicate rule id {rule_id}")
            seen.add(rule_id)
            link = f"[{rule_id}]({path.name}{anchor(rule_id, path)})"
            if has_since:
                lines.append(f"| {link} | {summary} | {since} | {apply} |")
            else:
                lines.append(f"| {link} | {summary} | {apply} |")
            total += 1
        lines.append("")
    lines.insert(6, f"**{total} rules in {len([p for p in files if rows_of(p)])} files.**")
    lines.insert(7, "")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(GUIDE.parent)}: {total} rules")


if __name__ == "__main__":
    main()
